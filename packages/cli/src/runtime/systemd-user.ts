/**
 * The header this product stamps into every systemd file it generates, and the ONLY proof of
 * ownership the reconciler is allowed to act on.
 *
 * `~/.config/systemd/user` is a shared namespace: upstream `clawdi` writes units there too, on the
 * same machine, for the same person (P33-01). A name prefix therefore proves nothing -- it is a
 * coincidence two products can share -- so reclaim, disable and delete decisions are made from a
 * file's own bytes instead.
 *
 * Only this product's spelling is recognised. There is no production deployment of iforge to stay
 * compatible with (user directive, 2026-09-30), and upstream `clawdi`'s own generated header marks
 * ITS units: accepting that spelling would make this reconciler collect another product's install.
 */
export const GENERATED_RUNTIME_SYSTEMD_FILE_HEADER =
	"# Generated by iforge runtime init. Do not edit inside hosted runtime.";

export function isGeneratedRuntimeSystemdFile(contents: string): boolean {
	return contents.startsWith(GENERATED_RUNTIME_SYSTEMD_FILE_HEADER);
}

/**
 * The name prefix this product gives the systemd entries it installs.
 *
 * A name under THIS prefix has only ever been written by this fork, so it is self-evidently ours.
 * Upstream `clawdi` claims its own `clawdi-` prefix on the same machine, which this product never
 * reads (see `isOwnedRuntimeSystemdEntry`).
 */
export const RUNTIME_SYSTEMD_OWNED_NAME_PREFIX = "iforge-";

/**
 * The single ownership test every collector site shares. MIGR-01, T-03.3-14.
 *
 * An entry in a shared systemd root belongs to this product when its name carries the current
 * prefix, OR when the file itself carries this product's generated header. Nothing else counts --
 * in particular, a `clawdi-` name with no iforge header is another product's install, and
 * reclaiming, disabling or deleting it is a denial of service against software that never
 * mentioned us.
 *
 * The header check is passed as a THUNK rather than a boolean so each caller keeps the
 * short-circuit it already had: a name under the current prefix is decided without reading the
 * file at all, which matters where the sites walk a directory.
 *
 * The header branch is what covers a file this product wrote under a name it does not own -- the
 * generated base units and environment files that sit beside a third-party runtime's official
 * unit, named after THAT unit. They carry the header and they are ours.
 */
export function isOwnedRuntimeSystemdEntry(
	name: string,
	carriesGeneratedHeader: () => boolean,
): boolean {
	// The serve daemon's unit is ours, and is NOT runtime convergence's to collect. The exemption
	// is folded in here rather than repeated at each collector because it has to hold at all of
	// them: this predicate is the single ownership test seven sites share, and an exemption
	// applied at six of them is the shape of the defect it exists to prevent.
	//
	// It became load-bearing with the P33-20 move (03.3-05). Before it, `clawdi-serve.service`
	// matched neither branch and was skipped by accident; after it, `iforge-serve.service` matches
	// the cheap name branch, and without this line a hosted converge would delete the daemon unit
	// a user installed with `iforge daemon install`.
	if (isServeDaemonSystemdUnit(name)) return false;
	return name.startsWith(RUNTIME_SYSTEMD_OWNED_NAME_PREFIX) || carriesGeneratedHeader();
}

/**
 * The user-scope daemon unit basename `serve/installer.ts` owns.
 *
 * These are NOT runtime-convergence units, and the distinction is load-bearing rather than tidy.
 * They live in the same `~/.config/systemd/user` directory the reconciler walks, and since the
 * P33-20 move the current one begins with `RUNTIME_SYSTEMD_OWNED_NAME_PREFIX` -- so the ownership
 * predicate's cheap name branch says "ours", correctly, and the reconciler's stale-file collector
 * would then delete a laptop user's daemon unit for the crime of not being in the hosted desired
 * state. It IS ours; it is simply owned by a different subsystem with a different lifecycle.
 *
 * `isServeDaemonSystemdUnit` is the exemption every runtime collector applies.
 */
export const SERVE_DAEMON_SYSTEMD_UNIT_BASENAMES = ["iforge-serve"] as const;

/**
 * True for a unit filename that belongs to the serve daemon installer rather than to runtime
 * convergence — the singleton or any pre-singleton per-agent form.
 */
export function isServeDaemonSystemdUnit(name: string): boolean {
	// `.env` is stripped first: the collectors pass environment filenames through this same
	// predicate, and `iforge-serve.service.env` must be exempt for the same reason its unit is.
	let base = name.endsWith(".env") ? name.slice(0, -".env".length) : name;
	if (base.endsWith(".service")) base = base.slice(0, -".service".length);
	return SERVE_DAEMON_SYSTEMD_UNIT_BASENAMES.some(
		(candidate) => base === candidate || base.startsWith(`${candidate}-`),
	);
}

/**
 * The Files companion's systemd unit name, in ONE place.
 *
 * Three modules name this unit: the reconciler that writes it, the reconciler's own program-name
 * derivation (a map key and the subject of every error line about it), and the live-state snapshot
 * that captures it before a mutation so a rollback can put it back. Three literals are three
 * chances to disagree, and a disagreement is silent -- one module writes a unit the next does not
 * account for.
 *
 * It lives HERE rather than beside the writer because the snapshot module would otherwise import
 * the reconciler's entire module graph to learn one string.
 *
 */
export const RUNTIME_SYSTEMD_FILE_BROWSER_UNIT_NAME = `${RUNTIME_SYSTEMD_OWNED_NAME_PREFIX}files`;

/**
 * The three HOSTED SYSTEM-SCOPE units, in ONE place.
 *
 * Three modules name these — the reconciler's collect set, the live-state snapshot, and the
 * `runtime` command's unit reader. Same reasoning as the Files unit above: three literals are
 * three chances to disagree, and the disagreement is silent.
 */
export const RUNTIME_SYSTEM_UNIT_WATCH = "iforge-runtime-watch";
export const RUNTIME_SYSTEM_UNIT_DAEMON = "iforge-daemon";
export const RUNTIME_SYSTEM_UNIT_SIDECAR = "iforge-runtime-sidecar";

/**
 * The `.service` filenames, DERIVED from the base names above rather than restated.
 *
 * The writer passes a base name to `writeSystemdSystemUnit`, which appends the suffix; the
 * collect set and the snapshot compare filenames. Deriving one from the other is what stops a
 * future rename from moving the unit this product WRITES while leaving the set that decides what
 * it is willing to COLLECT pointing at the old name — which would orphan a unit on every host.
 */
export const RUNTIME_SYSTEM_UNIT_NAMES = [
	`${RUNTIME_SYSTEM_UNIT_WATCH}.service`,
	`${RUNTIME_SYSTEM_UNIT_DAEMON}.service`,
	`${RUNTIME_SYSTEM_UNIT_SIDECAR}.service`,
] as const;

/**
 * The drop-in file this product writes into a unit's `<unit>.service.d` directory.
 *
 * A drop-in is the ONE generated file whose name is the only thing a collector can search for: the
 * unit directory it sits in is named after a THIRD-PARTY unit (`openclaw-gateway.service.d`), so a
 * scan opens a path built from this constant. Any other `.conf` there is foreign.
 */
export const RUNTIME_SYSTEMD_DROP_IN_FILE = "10-iforge-hosted.conf";

/** Every drop-in filename a reader accepts: this product's one spelling. */
export const RUNTIME_SYSTEMD_DROP_IN_FILE_NAMES = [RUNTIME_SYSTEMD_DROP_IN_FILE] as const;

/** True for this product's generated drop-in filename. */
export function isRuntimeSystemdDropInFileName(name: string): boolean {
	return (RUNTIME_SYSTEMD_DROP_IN_FILE_NAMES as readonly string[]).includes(name);
}

/**
 * The hosted runtime OS user this process acts for. The fallback is `HOSTED_RUNTIME_USER`'s value,
 * restated because this module is imported below `hosted-runtime-contract.ts`; the two are pinned
 * equal by `packages/cli/tests/hosted-identity-move.test.ts`.
 */
export function runtimeUserName(): string {
	return process.env.CLAWDI_RUNTIME_USER?.trim() || "iforge";
}

export function runtimeUserSystemdEnvironment(uid: string): Record<string, string> {
	const runtimeDir = `/run/user/${uid}`;
	return {
		XDG_RUNTIME_DIR: runtimeDir,
		DBUS_SESSION_BUS_ADDRESS: `unix:path=${runtimeDir}/bus`,
	};
}
